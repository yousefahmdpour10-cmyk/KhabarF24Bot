# =========================
# تابع محاسبه اهمیت
# =========================


def calculate_importance(
        title="",
        summary="",
        category=""
):


    text = f"""
    {title}
    {summary}
    """.lower()



    # امتیاز پایه

    score = 2



    # =====================
    # ⚽ ورزش اختصاصی
    # =====================

    if category == "sport":


        sport_score = calculate_sport_score(

            title,

            summary

        )


        return sport_score





    # =====================
    # سایر دسته‌ها
    # =====================


    for cat, words in IMPORTANCE_WORDS.items():


        hits = 0


        for word in words:


            if word.lower() in text:

                hits += 1



        if hits > 0:


            score += hits



            # سیاست وزن بیشتر

            if cat == "politics":

                score += 2



            # اقتصاد و فناوری

            if cat in [
                "economy",
                "technology"
            ]:

                score += 1





    # سقف

    if score > 10:

        score = 10



    return round(score,1)







# =========================
# تصمیم انتشار
# =========================


def is_important(
        title="",
        summary="",
        category="",
        minimum=7
):


    score = calculate_importance(

        title,

        summary,

        category

    )


    print(
        f"🔥 Importance Score: {score}/10"
    )



    return score >= minimum
