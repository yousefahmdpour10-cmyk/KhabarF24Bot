def calculate_importance(title="", summary=""):


    text = f"{title} {summary}".lower()


    score = 2



    for category, words in IMPORTANCE_WORDS.items():


        hits = 0


        for word in words:


            if word.lower() in text:

                hits += 1



        if hits:


            # افزایش امتیاز بر اساس تعداد کلیدواژه

            score += hits * 1



            # سیاسی و امنیتی وزن بالاتر

            if category == "politics":

                score += 2



            # اقتصاد و ورزش هم مهم هستند

            if category in [
                "economy",
                "sport"
            ]:

                score += 1






    if score > 10:

        score = 10



    if score < 1:

        score = 1



    return round(score, 1)








def is_important(title="", summary="", minimum=7):


    score = calculate_importance(

        title,

        summary

    )


    print(
        f"🔥 Importance Score: {score}/10"
    )


    return score >= minimum
