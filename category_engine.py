def detect_smart_category(
        title="",
        summary="",
        source=""
):


    text = f"""

    {title}

    {summary}

    {source}

    """.lower()



    scores = {}



    for category, keywords in CATEGORIES.items():


        score = 0


        for word in keywords:


            if word.lower() in text:

                score += 1



        scores[category] = score






    # سیاست اولویت مطلق دارد

    if scores.get(
        "politics",
        0
    ) >= 1:

        return "politics"





    for category in CATEGORY_PRIORITY:


        if scores.get(
            category,
            0
        ) > 0:

            return category






    return "world"
