def detect_smart_category(
        title="",
        summary="",
        source=""
):


    text = f"""

    {title}

    {summary}

    {source}

    """.lower()



    scores = {}



    for category, keywords in CATEGORIES.items():


        score = 0


        for word in keywords:


            if word.lower() in text:

                score += 1



        scores[category] = score





    # سیاست اولویت بالا دارد

    if scores.get("politics",0) > 0:

        return "politics"





    # ورزش بعد از سیاست

    if scores.get("sport",0) > 0:

        return "sport"





    for category in CATEGORY_PRIORITY:


        if scores.get(category,0) > 0:

            return category





    return "world"
