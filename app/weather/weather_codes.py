# ============================================================
# وضعیت پیش‌فرض
# ============================================================

DEFAULT_WEATHER = ("🌡️", "نامشخص")


# ============================================================
# دریافت وضعیت
# ============================================================

def get_weather_info(code: int) -> Tuple[str, str]:
    """
    کد Open-Meteo را به ایموجی و وضعیت فارسی تبدیل می‌کند.

    مثال:

        get_weather_info(61)

    خروجی:

        ("🌧️", "باران")
    """

    try:
        code = int(code)
    except (TypeError, ValueError):
        return DEFAULT_WEATHER

    return WEATHER_CODES.get(
        code,
        DEFAULT_WEATHER
    )


# ============================================================
# فقط ایموجی
# ============================================================

def get_weather_icon(code: int) -> str:
    """
    فقط ایموجی وضعیت هوا را برمی‌گرداند.
    """

    icon, _ = get_weather_info(code)

    return icon


# ============================================================
# فقط متن فارسی
# ============================================================

def get_weather_description(code: int) -> str:
    """
    فقط توضیح فارسی وضعیت هوا را برمی‌گرداند.
    """

    _, description = get_weather_info(code)

    return description
