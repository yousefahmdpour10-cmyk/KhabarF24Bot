def get_flag(source, country=None, flag=None):
    """
    تعیین پرچم منبع خبری.
    اولویت: پرچم صریح منبع، کد کشور، سپس نام رسانه.
    """

    if flag and str(flag).strip() not in ("🌍", ""):
        return str(flag).strip()

    if country:
        country_code = str(country).strip().upper()
        country_flag = COUNTRY_FLAGS.get(country_code)
        if country_flag:
            return country_flag

    if not source:
        return "🌍"

    name = str(source).strip().casefold()
    if not name:
        return "🌍"

    matched = _NORMALIZED_FLAGS.get(name)
    if matched:
        return matched

    # تطبیق نام‌های دارای پسوند، مانند "BBC Football RSS"
    for known_name in sorted(
        _NORMALIZED_FLAGS,
        key=len,
        reverse=True,
    ):
        if (
            name.startswith(known_name + " ")
            or name.endswith(" " + known_name)
        ):
            return _NORMALIZED_FLAGS[known_name]

    return "🌍"
