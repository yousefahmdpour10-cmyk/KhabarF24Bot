"""
مدل منبع خبری

تمام منابع خبری پروژه KhabarF24 باید از این مدل استفاده کنند.
"""

from dataclasses import dataclass, field
from typing import List


@dataclass
class NewsSource:
    """
    مدل اطلاعات یک منبع خبری.

    این مدل اجازه می‌دهد هر منبع چند روش دریافت داشته باشد:
    RSS → Website → API → Social
    """

    # ==========================================================
    # اطلاعات اصلی
    # ==========================================================

    # شناسه یکتا
    id: str

    # نام منبع
    name: str

    # نوع اصلی منبع
    # rss / website / api / social
    source_type: str

    # آدرس اصلی منبع
    url: str

    # کشور
    country: str

    # پرچم کشور
    flag: str

    # زبان
    language: str

    # ==========================================================
    # آدرس‌های اختصاصی
    # ==========================================================

    # آدرس RSS
    #
    # اگر منبع RSS نداشته باشد:
    # None
    rss_url: str | None = None

    # آدرس API
    api_url: str | None = None

    # آدرس وب‌سایت اصلی
    website_url: str | None = None

    # آدرس منبع اجتماعی
    # Telegram / X / ... در صورت وجود
    social_url: str | None = None

    # ==========================================================
    # قابلیت‌های منبع
    # ==========================================================

    # آیا RSS دارد؟
    has_rss: bool = False

    # آیا API دارد؟
    has_api: bool = False

    # آیا امکان Web Scraping دارد؟
    supports_scraping: bool = False

    # آیا برای دریافت اطلاعات نیاز به مرورگر دارد؟
    requires_browser: bool = False

    # آیا نیاز به ورود / Token دارد؟
    requires_auth: bool = False

    # ==========================================================
    # روش‌های جایگزین
    # ==========================================================

    # روش‌هایی که در صورت شکست روش اصلی
    # می‌توان امتحان کرد.
    #
    # مثال:
    # ["website", "social"]
    #
    # یعنی:
    # RSS شکست خورد
    # ↓
    # Website
    # ↓
    # Social
    fallback_types: List[str] = field(default_factory=list)

    # ==========================================================
    # دسته‌های خبری
    # ==========================================================

    # مثال:
    # ["sport", "football", "transfer"]
    categories: List[str] = field(default_factory=list)

    # ==========================================================
    # تنظیمات منبع
    # ==========================================================

    # میزان اعتبار / اولویت منبع
    # بازه پیشنهادی: 0 تا 100
    priority: int = 50

    # فاصله بررسی خبر بر حسب ثانیه
    check_interval: int = 60

    # فعال یا غیرفعال بودن منبع
    enabled: bool = True
