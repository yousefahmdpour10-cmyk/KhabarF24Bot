"""
مدل منبع خبری

تمام منابع خبری پروژه KhabarF24 باید از این مدل استفاده کنند.
"""

from dataclasses import dataclass, field
from typing import List


@dataclass
class NewsSource:
    """
    مدل اطلاعات یک منبع خبری.

    هر منبع می‌تواند چند روش دریافت داشته باشد:
    RSS → Website → API → Social
    """

    # ==========================================================
    # اطلاعات اصلی
    # ==========================================================

    id: str
    name: str
    source_type: str

    url: str

    country: str
    flag: str
    language: str

    # ==========================================================
    # آدرس‌های اختصاصی
    # ==========================================================

    rss_url: str | None = None
    api_url: str | None = None
    website_url: str | None = None
    social_url: str | None = None

    # ==========================================================
    # پلتفرم اجتماعی
    # ==========================================================

    social_platform: str = ""

    # ==========================================================
    # قابلیت‌ها
    # ==========================================================

    has_rss: bool = False
    has_api: bool = False

    supports_scraping: bool = False
    requires_browser: bool = False
    requires_auth: bool = False

    # ==========================================================
    # روش‌های جایگزین دریافت
    # ==========================================================

    fallback_types: List[str] = field(
        default_factory=list
    )

    # ==========================================================
    # دسته‌های خبری
    # ==========================================================

    categories: List[str] = field(
        default_factory=list
    )

    # ==========================================================
    # تنظیمات
    # ==========================================================

    priority: int = 50

    check_interval: int = 60

    enabled: bool = True
