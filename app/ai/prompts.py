"""
app/ai/prompts.py

پرامپت واحد برای تولید هم‌زمان «تیتر فارسی روان و کامل» و «خلاصه‌ی فارسی
روان» از روی عنوان و متن خام یک خبر (به هر زبانی که باشد).

چرا یک پرامپت واحد؟
  - یک فراخوانی API به‌جای دو/سه‌تا -> مصرف کمتر سهمیه‌ی رایگان Gemini
  - تیتر و خلاصه هماهنگ با هم تولید می‌شوند (لحن و کلمات یکسان)

خروجی مدل باید دقیقاً یک JSON با دو کلید باشد:
    {"headline": "...", "summary": "..."}
Parse کردن این JSON مسئولیت app/ai/content_generator.py است، نه این فایل.
"""

MAX_CONTENT_CHARS = 4000  # جلوگیری از پرامپت‌های خیلی بزرگ (هزینه/سرعت)


def build_content_prompt(title: str, content: str) -> str:
    """
    ساخت پرامپت نهایی برای ارسال به Gemini.

    title:    عنوان خام خبر (هر زبانی)
    content:  متن/خلاصه‌ی خام خبر (هر زبانی)
    """
    trimmed_content = (content or "").strip()[:MAX_CONTENT_CHARS]

    return f"""تو یک ویراستار حرفه‌ای خبری فارسی‌زبان هستی. وظیفه‌ات تولید یک
تیتر و یک خلاصه‌ی خبری فارسیِ کاملاً روان و طبیعی است — نه ترجمه‌ی
کلمه‌به‌کلمه. اگر متن ورودی به زبان دیگری غیر از فارسی است، آن را به
فارسیِ رسانه‌ای معمول (لحن خبرگزاری‌های ایرانی) بازنویسی کن.

قوانین:
۱. «headline»: یک جمله‌ی کامل، کوتاه، جذاب و کاملاً مفهوم به فارسی.
   - هرگز نباید ناقص یا بریده باشد.
   - حداکثر ۱۵ کلمه.
   - بدون علامت نقل‌قول، بدون ** یا هر نشانه‌ی قالب‌بندی.
۲. «summary»: خلاصه‌ای در ۲ تا ۴ جمله‌ی روان فارسی که مهم‌ترین نکات خبر
   را پوشش دهد؛ بدون اضافه کردن اطلاعاتی که در متن اصلی نیست.
۳. اسم افراد، مکان‌ها، سازمان‌ها و اعداد/تاریخ‌ها را دقیق و بدون تغییر
   منتقل کن.
۴. فقط و فقط یک JSON خام و معتبر با همین دو کلید برگردان — هیچ توضیح
   اضافه، هیچ متن قبل یا بعد از JSON، و بدون ```json.

فرمت خروجی:
{{"headline": "...", "summary": "..."}}

---
عنوان خام:
{title.strip()}

متن خام:
{trimmed_content}
---
"""
